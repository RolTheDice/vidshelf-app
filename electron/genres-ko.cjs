// 장르라기보다 판매·화질·행사 표시라서 빼는 것
const SKIP = new Set(['ハイビジョン', '独占配信', 'サンプル動画', '4K', 'FANZA配信限定', 'DMM独占', '配信専用', '先行販売', '期間限定セール', 'デジモ', 'ギリモザ']);
const SKIP_RE = /セール|オフ|割引|キャンペーン|限定|配信|ポイント|Sale|Off\b/i;

/**
 * r18.dev categories → 한국어 장르 목록
 * @param {{name_ja?:string, name_en?:string, name?:string}[]} categories
 */
function mapGenres(categories) {
  const out = [];
  for (const c of categories || []) {
    const ja = (c && c.name_ja) || '';
    const en = (c && (c.name_en || c.name)) || '';
    if (!ja && !en) continue;
    if (SKIP.has(ja) || SKIP_RE.test(ja) || SKIP_RE.test(en) || /^(Sample Video|Hi-Def|Exclusive Distribution)$/i.test(en)) continue;
    const ko = GENRE_KO[ja] || en || ja;
    if (!out.includes(ko)) out.push(ko);
  }
  return out;
}

module.exports = { mapGenres, GENRE_KO };
